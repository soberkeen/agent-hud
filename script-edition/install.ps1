# install.ps1 — HDR 开关 安装脚本：生成图标 + 桌面快捷方式（可选开机自启）
# 用法:
#   .\install.ps1            创建桌面快捷方式（首次会生成 hdr-toggle.ico）
#   .\install.ps1 -Startup   额外复制到 shell:startup 实现开机自启
#   .\install.ps1 -Remove    移除桌面快捷方式与自启项
param(
    [switch]$Startup,
    [switch]$Remove
)

$ErrorActionPreference = 'Stop'

$lnkName   = 'HDR 开关.lnk'
$scriptPath = Join-Path $PSScriptRoot 'hdr-toggle.ps1'
$icoPath    = Join-Path $PSScriptRoot 'hdr-toggle.ico'
$desktop    = [Environment]::GetFolderPath('Desktop')
$lnkPath    = Join-Path $desktop $lnkName
$startupLnk = Join-Path ([Environment]::GetFolderPath('Startup')) $lnkName

if ($Remove) {
    foreach ($p in @($lnkPath, $startupLnk)) {
        if (Test-Path $p) { Remove-Item $p -Force; "已移除: $p" }
    }
    return
}

if (-not (Test-Path $scriptPath)) { throw "未找到主程序: $scriptPath" }

# 生成无窗口启动器：本机默认终端是 Windows Terminal，直接以 pwsh 为快捷方式目标
# 会留下可见的 WT 窗口；wscript 的 Run(...,0) 以 SW_HIDE 启动可完全无窗口。
# 脚本路径经快捷方式参数传入（VBS 本身保持纯 ASCII，避免中文路径被编码损坏）
$vbsPath = Join-Path $PSScriptRoot 'launch.vbs'
@'
' launch.vbs - headless launcher (generated by install.ps1)
' usage: wscript.exe launch.vbs "<script path>"
Dim sh, pwsh
Set sh = CreateObject("WScript.Shell")
pwsh = sh.ExpandEnvironmentStrings("%ProgramFiles%\PowerShell\7\pwsh.exe")
sh.Run """" & pwsh & """ -NoProfile -STA -WindowStyle Hidden -File """ & WScript.Arguments(0) & """", 0, False
'@ | Set-Content $vbsPath -Encoding ASCII
"已写入启动器: $vbsPath"

# 生成图标：深色圆底 + 绿描边 + HDR 字样（PNG 载荷的 ICO 容器）
if (-not (Test-Path $icoPath)) {
    Add-Type -AssemblyName System.Drawing
    $size = 64
    $bmp = New-Object System.Drawing.Bitmap($size, $size)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = 'AntiAlias'
    $g.Clear([System.Drawing.Color]::Transparent)
    $g.FillEllipse((New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(224, 51, 51, 51))), 2, 2, 60, 60)
    $g.DrawEllipse((New-Object System.Drawing.Pen([System.Drawing.Color]::FromArgb(255, 124, 252, 158), 3)), 4, 4, 56, 56)
    $fmt = New-Object System.Drawing.StringFormat
    $fmt.Alignment = 'Center'; $fmt.LineAlignment = 'Center'
    $g.DrawString('HDR', (New-Object System.Drawing.Font('Segoe UI', 16, [System.Drawing.FontStyle]::Bold)),
        (New-Object System.Drawing.SolidBrush([System.Drawing.Color]::FromArgb(255, 124, 252, 158))),
        (New-Object System.Drawing.RectangleF(0, 2, 64, 60)), $fmt)
    $g.Dispose()
    $ms = New-Object System.IO.MemoryStream
    $bmp.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png)
    $png = $ms.ToArray(); $ms.Dispose(); $bmp.Dispose()
    $bw = New-Object System.IO.BinaryWriter([System.IO.File]::Create($icoPath))
    $bw.Write([uint16]0); $bw.Write([uint16]1); $bw.Write([uint16]1)          # ICONDIR: 1 个图标
    $bw.Write([byte]$size); $bw.Write([byte]$size); $bw.Write([byte]0); $bw.Write([byte]0)
    $bw.Write([uint16]1); $bw.Write([uint16]32)                                # PNG 载荷
    $bw.Write([uint32]$png.Length); $bw.Write([uint32]22)                      # 数据偏移 = 6+16
    $bw.Write($png); $bw.Dispose()
    "已生成图标: $icoPath"
}

# 桌面快捷方式 → wscript 无窗口启动器（图标用自生成的 hdr-toggle.ico）
$ws  = New-Object -ComObject WScript.Shell
$lnk = $ws.CreateShortcut($lnkPath)
$lnk.TargetPath      = Join-Path $env:SystemRoot 'System32\wscript.exe'
$lnk.Arguments       = "`"$vbsPath`" `"$scriptPath`""
$lnk.WorkingDirectory = $PSScriptRoot
$lnk.IconLocation    = "$icoPath,0"
$lnk.Description      = '一键开关主显示器 HDR'
$lnk.Save()
"已创建桌面快捷方式: $lnkPath"

if ($Startup) {
    Copy-Item $lnkPath $startupLnk -Force
    "已加入开机自启: $startupLnk"
}
